def test_fixture_carries_no_real_secrets_and_no_local_paths(generation):
    """A regression guard on the fixture, not on any reader.

    Every secret-shaped value is an obviously-fake ``TEST-NOT-A-REAL-*``
    string, and no path from the generating machine survives the scrub. The
    tarball is decompressed first — gzip would hide a leak from a raw scan.
    """
    forbidden = ("/Users/", "/tmp/agentcage-state-fixture-")
    # ``/home/node`` and ``/home/acproxy`` are paths *inside* the workload and
    # egress containers, not host paths.
    allowed_homes = {"agentcage-fixture", "node", "acproxy"}
    for path in sorted(generation.rglob("*")):
        if not path.is_file():
            continue
        blob = path.read_bytes()
        if path.suffix == ".gz":
            blob = gzip.decompress(blob)
        text = blob.decode("utf-8", "replace")
        for needle in forbidden:
            assert needle not in text, f"{path.name} leaks {needle!r}"
        found = set(re.findall(r"/home/([A-Za-z0-9._-]+)", text))
        assert found <= allowed_homes, f"{path.name} leaks home dirs: {found}"


