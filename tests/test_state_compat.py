def test_load_raw_config_secret_injection_shapes(state):
    """Three rules, three different secret sources, one minted placeholder."""
    rules = state.load_raw_config(RICH)["secret_injection"]
    assert [r["env"] for r in rules] == [
        "ANTHROPIC_API_KEY", "GITHUB_TOKEN", "IMAP_PASSWORD",
    ]
    assert rules[0]["source"] == "systemd-creds:ANTHROPIC_API_KEY"
    assert rules[0]["inject_headers"] == ["x-api-key"]
    assert rules[0]["inject_body"] is False
    assert rules[1]["source"] == "env:FIXTURE_GITHUB_TOKEN"
    assert rules[1]["inject_to"] == ["github.com", "*.githubusercontent.com"]
    # This rule omitted ``placeholder:`` in the operator's file;
    # ``fill_placeholders`` minted one and rewrote cage.yaml. The token must
    # be present, prefixed, and carry 32 hex characters of entropy.
    minted = rules[2]["placeholder"]
    assert minted.startswith("agentcage:secret:IMAP_PASSWORD:")
    suffix = minted.rsplit(":", 1)[1]
    assert len(suffix) == 32 and int(suffix, 16) >= 0
    assert "source" not in rules[2]


