def test_capture_jsonl_round_trips_through_the_har_builder(state):
    from agentcage.har import capture_to_har

    lines = state.capture_file(RICH).read_text().splitlines()
    entries = [json.loads(line) for line in lines]
    assert len(entries) == 2

    first = entries[0]
    assert first["flow_id"] == "fixture-flow-0001"
    assert first["decision"] == "allowed"
    assert first["host"] == "api.anthropic.com"
    assert first["direction"] == "outbound"
    # Headers are [name, value] pairs, and both perspectives are recorded:
    # inbound keeps the placeholder, outbound has the wire value.
    inbound_headers = dict(map(tuple, first["inbound"]["request"]["headers"]))
    outbound_headers = dict(map(tuple, first["outbound"]["request"]["headers"]))
    assert inbound_headers["x-api-key"].startswith(
        "agentcage:secret:ANTHROPIC_API_KEY:"
    )
    assert outbound_headers["x-api-key"] == "TEST-NOT-A-REAL-SECRET-0001"

    assert entries[1]["decision"] == "blocked"
    assert entries[1]["inspectors"][0]["name"] == "domain"
    assert entries[1]["outbound"]["response"] == {}

    har = capture_to_har(entries, view="inbound")
    assert har["log"]["version"] == "1.2"
    assert len(har["log"]["entries"]) == 2
    assert har["log"]["entries"][0]["request"]["url"] == (
        "https://api.anthropic.com/v1/messages"
    )
    assert har["log"]["entries"][0]["response"]["status"] == 200

    outbound_har = capture_to_har(entries, view="outbound")
