"""On-disk state-compatibility tests against committed Python-written state.

Why these exist
---------------
The host CLI is being rewritten in Rust (``RUST-PORT-PLAN.md`` §2.7). At
cutover, every existing user has cages that the *Python* CLI deployed, and the
Rust binary must read that state **in place, on first run, with no migration
step**. None of it carries a schema version — ``metadata.json`` is a bare
``json.dumps(dict)`` and there is no ``state_version`` field anywhere in
``state.py`` — so there is nothing to branch on. The Rust readers simply have
to accept exactly what the Python writers produce.

``tests/fixtures/state-compat/<version>/`` is a byte-frozen snapshot of that
output, generated by ``scripts/gen-state-fixtures.py``. Everything below loads
those bytes through the real Python readers and asserts **concrete expected
values**, not merely "does not raise". That is deliberate: these assertions are
the specification the Rust implementation will later be held to, and a test
that only proves the parser did not crash proves nothing about the format.

Every test is parametrized over *all* committed generations. A new agentcage
version adds a directory rather than replacing one, so the Rust reader can be
held to several generations of on-disk state at once.
"""

from __future__ import annotations

import gzip
import json
import re
import shutil
import tarfile
from pathlib import Path
from unittest import mock

import pytest
import yaml

FIXTURE_ROOT = Path(__file__).parent / "fixtures" / "state-compat"

#: The cage names the generator emits. Kept in sync via MANIFEST.json, which
#: every generation carries.
RICH = "acme-agent"
MINIMAL = "plain-cage"
APPLE = "mac-agent"

#: The stand-in home the generator scrubs every real path down to.
SCRUB_HOME = "/home/agentcage-fixture"


def _generations() -> list[str]:
    if not FIXTURE_ROOT.is_dir():
        return []
    return sorted(p.name for p in FIXTURE_ROOT.iterdir() if p.is_dir())


GENERATIONS = _generations()

pytestmark = pytest.mark.skipif(
    not GENERATIONS, reason="no state-compat fixtures committed"
)


@pytest.fixture(params=GENERATIONS or [None], ids=lambda v: f"gen-{v}")
def generation(request) -> Path:
    """One committed fixture generation, as a directory path."""
    return FIXTURE_ROOT / request.param


@pytest.fixture
def state(generation, tmp_path, monkeypatch):
    """``agentcage.state`` pointed at a throwaway copy of *generation*.

    A copy rather than the committed tree itself: several readers
    (``capture_dir``, ``grants_dir``, ``cage_data_dir``) ``mkdir`` on the way
    in, and a test run must not mutate a committed fixture.
    """
    import agentcage.state as _state

    shutil.copytree(generation / "xdg-config", tmp_path / "config")
    shutil.copytree(generation / "xdg-data", tmp_path / "data")

    monkeypatch.setattr(_state, "_CONFIG_DIR", tmp_path / "config" / "agentcage")
    monkeypatch.setattr(
        _state, "_DEPLOYMENTS_DIR", tmp_path / "config" / "agentcage" / "cages"
    )
    monkeypatch.setattr(_state, "_DATA_DIR", tmp_path / "data" / "agentcage")
    return _state


