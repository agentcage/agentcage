def test_cage_restore_of_the_fixture_tarball(generation, tmp_path, monkeypatch):
    """``cage restore --no-start`` rebuilds a full state dir from the tarball.

    This is the D11 acceptance path: the Rust implementation has to restore a
    tarball a *Python* agentcage produced.
    """
    from click.testing import CliRunner

    import agentcage.cli as cli
    import agentcage.state as _state

    home = tmp_path / "home"
    (home / ".config" / "agentcage").mkdir(parents=True)
    # The restored cage.yaml declares ``upstream.ca_file: ~/fixture-ca.pem``,
    # which save_proxy_config reads and inlines. Provide it under the fake
    # home rather than weakening the test by stubbing the resolver out.
    (home / "fixture-ca.pem").write_text(
        "-----BEGIN CERTIFICATE-----\n"
        "TEST-NOT-A-REAL-CERTIFICATE-0001\n"
        "-----END CERTIFICATE-----\n"
    )
    monkeypatch.setenv("HOME", str(home))
    monkeypatch.setattr(
        _state, "_CONFIG_DIR", home / ".config" / "agentcage"
    )
    monkeypatch.setattr(
        _state, "_DEPLOYMENTS_DIR", home / ".config" / "agentcage" / "cages"
    )
    monkeypatch.setattr(
        _state, "_DATA_DIR", home / ".local" / "share" / "agentcage"
    )

    podman = mock.MagicMock()
    podman.secret_exists.return_value = False

    with mock.patch.object(cli, "_podman_for_cage", return_value=podman):
        result = CliRunner().invoke(
            cli.main,
            ["cage", "restore", str(_tarball(generation)),
             "--name", "restored", "--no-start"],
        )

    assert result.exit_code == 0, result.output
    assert "Cage state restored" in result.output

    # Secrets were included, so they are pushed back into the podman store.
    created = {c.args[0]: c.args[1] for c in podman.secret_create.call_args_list}
    assert created == {
        "restored.ANTHROPIC_API_KEY": "TEST-NOT-A-REAL-SECRET-0001",
        "restored.GITHUB_TOKEN": "TEST-NOT-A-REAL-SECRET-0003",
        "restored.IMAP_PASSWORD": "TEST-NOT-A-REAL-SECRET-0004",
    }

    # State dir rebuilt, with the name rewritten and derived files regenerated.
    assert _state.deployment_exists("restored")
    raw = _state.load_raw_config("restored")
    assert raw["name"] == "restored"
    assert raw["domains"]["allow"][0] == "api.anthropic.com"
    assert _state.load_metadata("restored")["agentcage_version"] == generation.name

    proxy = yaml.safe_load(
        (_state.deployment_dir("restored") / "proxy-config.yaml").read_text()
    )
    assert "container" not in proxy
    assert proxy["protocol_relays"][0]["upstream"]["ca_pem"].startswith(
        "-----BEGIN CERTIFICATE-----"
    )
    dns = _state.dns_allowlist_path("restored").read_text().splitlines()
    assert "server=/api.anthropic.com/1.1.1.1" in dns


# ── the fixture must survive a fresh checkout ──────────────


def test_fixture_has_no_empty_directories(generation):
    """git cannot represent an empty directory.

    One that the generator emitted would live on in the author's working tree,
    be silently dropped by ``git add``, and then make the regeneration check
    below fail on every fresh checkout while passing locally. This test fails
    on the generating machine — which is the only place it can be fixed.
    """
    empty = sorted(
        str(d.relative_to(generation))
        for d in generation.rglob("*")
        if d.is_dir() and not any(d.iterdir())
    )
    assert empty == [], (
        "these directories cannot be committed and will make CI diverge "
        "from a local run"
    )


def test_every_fixture_file_is_tracked_by_git():
    """The same trap as empty directories, for files.

    A fixture file that exists locally but was never ``git add``-ed passes
    every local check and is simply absent on CI. Compare what is on disk
    against what git actually has.
    """
    import subprocess

    repo = Path(__file__).parent.parent
    try:
        listed = subprocess.run(
            ["git", "ls-files", "-z", "--", "tests/fixtures/state-compat"],
            cwd=repo, capture_output=True, text=True,
        )
    except OSError:  # pragma: no cover — git not installed
        pytest.skip("git is not available")
    if listed.returncode != 0:  # pragma: no cover — not a git checkout
        pytest.skip("not a git checkout")

    tracked = {p for p in listed.stdout.split("\0") if p}
    on_disk = {
        str(p.relative_to(repo))
        for p in (FIXTURE_ROOT).rglob("*") if p.is_file()
    }
    assert on_disk - tracked == set(), "untracked fixture files"
    assert tracked - on_disk == set(), "tracked fixture files missing on disk"


def _package_version() -> str | None:
    from importlib.metadata import PackageNotFoundError, version

    try:
        return version("agentcage")
    except PackageNotFoundError:  # pragma: no cover — uninstalled checkout
        return None


@pytest.mark.skipif(
    _package_version() is None,
    reason="agentcage is not installed; the generator cannot stamp a version",
)
def test_generator_reproduces_the_committed_fixture_byte_for_byte():
    """Re-running the generator must produce an identical tree.

    Determinism is the whole point: a fixture that drifts on every run is
    worthless as a format specification. This is also the guard that catches
    a writer change landing without a fixture regeneration.

    Only the generation matching the *installed* version is checked — older
    generations are snapshots of code that no longer exists here.

    On failure the generator prints a per-file report (added / removed /
    changed, with a unified diff, and for the backup tarball a comparison of
    decompressed members rather than the gzip stream). It is relayed verbatim
    so a CI log is enough to diagnose the drift without reproducing it.
    """
    import subprocess
    import sys

    version = _package_version()
    if version not in GENERATIONS:
        # The stamp comes from importlib.metadata, which after PR A1 resolves
        # from the root VERSION file. A version bump is therefore expected to
        # land here exactly once, and the fix is to add a generation rather
        # than to edit an existing one.
        pytest.skip(
            f"no committed fixture for the installed version {version}; "
            f"committed generations are {GENERATIONS}. If the version was "
            f"just bumped, add a generation:\n"
            f"    uv run python scripts/gen-state-fixtures.py"
        )

    repo = Path(__file__).parent.parent
    result = subprocess.run(
        [sys.executable, str(repo / "scripts" / "gen-state-fixtures.py"), "--check"],
        capture_output=True,
        text=True,
        cwd=repo,
    )
    assert result.returncode == 0, (
        "\n\nThe committed fixture no longer matches what the generator "
        "produces.\nIf the change is intended, re-run:\n"
        "    uv run python scripts/gen-state-fixtures.py\n\n"
        + result.stderr
        + "\n"
        + result.stdout
    )
