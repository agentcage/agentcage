def test_pending_secrets_is_a_list_of_pairs(state):
    """``pending_secrets.json`` is ``[[key, value], …]`` — not an object.

    Both writers agree on this: ``ApplePlaintextStore._save`` and the VM
    hand-off in ``cli.py``. A Rust reader that assumed a JSON map would fail
    on every cage that has ever used either path.
    """
    from agentcage.secret_store import ApplePlaintextStore

    raw = json.loads(
        (state.deployment_dir(RICH) / "pending_secrets.json").read_text()
    )
    assert isinstance(raw, list)
    assert raw == [["GITHUB_TOKEN", "TEST-NOT-A-REAL-SECRET-0003"]]

    store = ApplePlaintextStore()
    d = state.deployment_dir(RICH)
    assert store.names(RICH, state_dir=d) == ["GITHUB_TOKEN"]
    assert store.get(RICH, "GITHUB_TOKEN", state_dir=d) == (
        "TEST-NOT-A-REAL-SECRET-0003"
    )
    assert store.get(RICH, "NOPE", state_dir=d) is None


def test_cred_blobs_presence_and_shape_only(state):
    """``creds/<key>.cred`` — shape only; the contents cannot be decrypted.

    systemd-creds encryption is host-bound (host key / TPM2 / per-user key),
    so this blob is opaque everywhere except the machine that made it. The
    Rust port has the same obligation the Python has: find the file, hand it
    to ``systemd-creds decrypt``, never parse it.
    """
    creds = state.deployment_dir(RICH) / "creds"
    assert sorted(p.name for p in creds.iterdir()) == [
        "ANTHROPIC_API_KEY.cred", "IMAP_PASSWORD.cred", "OPENROUTER_API_KEY.cred",
    ]
    blob = (creds / "ANTHROPIC_API_KEY.cred").read_bytes()
    assert len(blob) > 64
    # base64 armor, as ``systemd-creds encrypt … -`` emits it.
    assert blob.decode().replace("\n", "").isalnum() or b"/" in blob


