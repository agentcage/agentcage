//! agentcage's on-disk state, and the systemd unit lifecycle on top of
//! it.
//!
//! # The problem this crate exists to solve
//!
//! Hosts upgrading from earlier releases have cages those releases
//! deployed, and the binary has to read that state in place, on its
//! first invocation, with no migration step. None of it carries a
//! schema version — `metadata.json` is a bare JSON object and there is
//! no `state_version` field anywhere — so there is nothing to branch
//! on. These readers simply have to accept exactly what the earlier
//! writers produced.
//!
//! "Exactly what the earlier writers produced" is not a judgement call
//! here: PR A7 committed a byte-frozen snapshot of it at
//! `tests/fixtures/state-compat/0.40.1/`, generated by driving the
//! real code paths for three cages, and `tests/state_compat.rs` reads
//! every file in it and asserts concrete values. That fixture is the
//! specification; this crate is held to it.
//!
//! # Layout
//!
//! | module | what it owns |
//! | :-- | :-- |
//! | [`paths`] | the **four** state roots and every path derived from them |
//! | [`atomic`] | `O_EXCL` + PID-suffixed temp + one retry, and why it never unlinks |
//! | [`deployment`] | the stored `cage.yaml` |
//! | [`metadata`] | the two JSON files, which disagree about everything |
//! | [`derived`] | the files regenerated on every deploy |
//! | [`grants`] | the Policy-API overlay and its audit trail |
//! | [`pending_secrets`] | the *format* of `pending_secrets.json` and `secret_keys.json`; the stores are D3's |
//! | [`systemd`] | which directory a unit file belongs in, and the reload after |
//! | [`path_expand`] | `~` and `$VAR` expansion (`os.path.expanduser` / `expandvars` semantics), each with a leave-it-alone branch |
//!
//! Most of the API is methods on [`Paths`], such as
//! `paths.load_raw_config(name)`.
//!
//! # Three things §2.7 gets subtly right and a reader will get wrong
//!
//! 1. The per-cage config directory is `.../agentcage/**cages**/<name>/`.
//! 2. The grants overlay is `grants/grants.**yaml**` — a top-level
//!    YAML **list**, not a JSON object.
//! 3. `pending_secrets.json` is a JSON array of `[key, value]`
//!    **pairs**, not an object.
//!
//! And two absences:
//!
//! * There is **no host-side `audit.jsonl`** for a `container` or `vm`
//!   cage. Only apple-container has one, at
//!   [`Paths::apple_audit_file`]; elsewhere the addon writes to stderr
//!   and the host reads `journalctl`.
//! * The apple-container root **ignores `XDG_CONFIG_HOME`** and
//!   expands `~` directly, so an XDG sandbox does not redirect it.
//!   [`Paths::under`] moves `HOME` too, for exactly this reason.
//!
//! # What is NOT in here
//!
//! Anything that decides *whether* to write. `cage update`'s
//! fingerprint comparison, the grants reconcile's promote/revoke
//! logic, the backup tarball — those are D6-D12, and they take a
//! [`Paths`] rather than reaching for a global.

