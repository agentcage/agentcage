//! `cargo xtask gen-packaging` — the Homebrew formula and the AUR
//! `PKGBUILD` for a release.
//!
//! Both files pin a version *and* a checksum for every platform, which
//! makes both of them wrong the moment a release ships and right again
//! only when someone regenerates them. Hand-copying four checksums per
//! release is how a tap ends up installing the previous version, so
//! neither file is committed in a filled-in state — this produces them
//! from the checksums the release actually published.
//!
//! Two sources, because there are two moments you need this:
//!
//! - `--dist DIR`: the assets a release build just produced, before
//!   anything is published;
//! - `--from-release`: the assets already attached to the GitHub
//!   release, which is what a maintainer updating a tap has.
//!
//! Writes `agentcage.rb` and `PKGBUILD` into `--out`. Neither is
//! committed to this repository; see `packaging/README.md` for where
//! they go.

use std::collections::BTreeMap;
use std::path::Path;
use std::process::ExitCode;

/// The GitHub repository releases are published from.
const REPO: &str = "agentcage/agentcage";

/// The four released targets.
const TARGETS: [&str; 4] = [
    "x86_64-unknown-linux-musl",
    "aarch64-unknown-linux-musl",
    "x86_64-apple-darwin",
    "aarch64-apple-darwin",
];

/// A release asset's file name.
fn asset(version: &str, target: &str) -> String {
    format!("agentcage-{version}-{target}.tar.gz")
}

/// The digest a `.sha256` file carries (its first field).
fn first_field(text: &str) -> Option<String> {
    text.split_whitespace().next().map(str::to_owned)
}

/// Checksums from a directory of built assets.
fn checksums_from_dist(
    version: &str,
    dist: &Path,
) -> Result<BTreeMap<&'static str, String>, String> {
    let mut sums = BTreeMap::new();
    for target in TARGETS {
        let path = dist.join(format!("{}.sha256", asset(version, target)));
        let text = std::fs::read_to_string(&path)
            .map_err(|_| format!("missing {} — was {target} built?", path.display()))?;
        let digest = first_field(&text).ok_or_else(|| format!("{} is empty", path.display()))?;
        sums.insert(target, digest);
    }
    Ok(sums)
}

/// Checksums read straight off the published release.
fn checksums_from_release(version: &str) -> Result<BTreeMap<&'static str, String>, String> {
    let mut sums = BTreeMap::new();
    for target in TARGETS {
        let url = format!(
            "https://github.com/{REPO}/releases/download/v{version}/{}.sha256",
            asset(version, target)
        );
        let text = ureq::get(&url)
            .call()
            .and_then(|mut response| response.body_mut().read_to_string())
            .map_err(|e| format!("could not read {url}: {e}"))?;
        let digest = first_field(&text).ok_or_else(|| format!("{url} is empty"))?;
        sums.insert(target, digest);
    }
    Ok(sums)
}

/// One `url`/`sha256` pair of the formula.
fn block(version: &str, sums: &BTreeMap<&str, String>, target: &str) -> String {
    format!(
        "      url \"https://github.com/{REPO}/releases/download/v{version}/{}\"\n      sha256 \"{}\"",
        asset(version, target),
        sums[target]
    )
}

/// The Homebrew formula.
///
/// `depends_on "podman"` is deliberate and deliberately not `:optional`:
/// agentcage without a container runtime starts nothing, and a formula
/// that installs a binary which cannot work is worse than one that pulls
/// a dependency the user may already have.
fn formula(version: &str, sums: &BTreeMap<&str, String>) -> String {
    format!(
        r##"# Generated by `cargo xtask gen-packaging` — do not hand-edit.
#
# Regenerate on every release:
#   cargo xtask gen-packaging --version <version> --from-release
class Agentcage < Formula
  desc "Defense-in-depth proxy sandbox for AI agents"
  homepage "https://github.com/{REPO}"
  version "{version}"
  license "MIT"

  depends_on "podman"

  on_macos do
    on_arm do
{mac_arm}
    end
    on_intel do
{mac_intel}
    end
  end

  on_linux do
    on_arm do
{linux_arm}
    end
    on_intel do
{linux_intel}
    end
  end

  def install
    bin.install "agentcage"
  end

  test do
    assert_match "agentcage, version #{{version}}", shell_output("#{{bin}}/agentcage --version")
  end
end
"##,
        mac_arm = block(version, sums, "aarch64-apple-darwin"),
        mac_intel = block(version, sums, "x86_64-apple-darwin"),
        linux_arm = block(version, sums, "aarch64-unknown-linux-musl"),
        linux_intel = block(version, sums, "x86_64-unknown-linux-musl"),
    )
}

/// The AUR `PKGBUILD`, as `agentcage-bin`.
///
/// `-bin` because it installs a released binary rather than building
/// from source, which is the AUR's naming rule and not a preference.
fn pkgbuild(version: &str, sums: &BTreeMap<&str, String>) -> String {
    format!(
        r#"# Generated by `cargo xtask gen-packaging` — do not hand-edit.
#
# Regenerate on every release, then `makepkg --printsrcinfo > .SRCINFO`:
#   cargo xtask gen-packaging --version <version> --from-release
#
# Maintainer: Luca Martinetti <luca@luca.io>
pkgname=agentcage-bin
pkgver={version}
pkgrel=1
pkgdesc="Defense-in-depth proxy sandbox for AI agents"
arch=('x86_64' 'aarch64')
url="https://github.com/{REPO}"
license=('MIT')
depends=('podman')
optdepends=('lima: microVM (isolation: vm) backend')
provides=('agentcage')
conflicts=('agentcage')

_base="$url/releases/download/v$pkgver"
source_x86_64=("$_base/{x86_asset}")
source_aarch64=("$_base/{arm_asset}")
sha256sums_x86_64=('{x86_sum}')
sha256sums_aarch64=('{arm_sum}')

package() {{
  local _target
  case "$CARCH" in
    x86_64)  _target=x86_64-unknown-linux-musl ;;
    aarch64) _target=aarch64-unknown-linux-musl ;;
  esac
  cd "agentcage-$pkgver-$_target"
  install -Dm755 agentcage "$pkgdir/usr/bin/agentcage"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
  install -Dm644 README.md "$pkgdir/usr/share/doc/$pkgname/README.md"
}}
"#,
        x86_asset = asset(version, "x86_64-unknown-linux-musl"),
        arm_asset = asset(version, "aarch64-unknown-linux-musl"),
        x86_sum = sums["x86_64-unknown-linux-musl"],
        arm_sum = sums["aarch64-unknown-linux-musl"],
    )
}

/// Render both files for `version` into `out`.
pub(crate) fn run(
    version: &str,
    dist: Option<&Path>,
    from_release: bool,
    out: &Path,
) -> Result<ExitCode, String> {
    let version = version.trim_start_matches('v');
    let sums = match (dist, from_release) {
        (_, true) => checksums_from_release(version)?,
        (Some(dist), false) => checksums_from_dist(version, dist)?,
        (None, false) => return Err("pass --dist DIR or --from-release".to_owned()),
    };
    std::fs::create_dir_all(out).map_err(|e| format!("{}: {e}", out.display()))?;
    for (name, text) in [
        ("agentcage.rb", formula(version, &sums)),
        ("PKGBUILD", pkgbuild(version, &sums)),
    ] {
        let path = out.join(name);
        std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
        println!("wrote {}", path.display());
    }
    for (target, digest) in &sums {
        println!(
            "  {target:32} {}...",
            digest.chars().take(16).collect::<String>()
        );
    }
    Ok(ExitCode::SUCCESS)
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeMap;

    use super::{TARGETS, asset, checksums_from_dist, formula, pkgbuild};

    fn sums() -> BTreeMap<&'static str, String> {
        TARGETS
            .iter()
            .enumerate()
            .map(|(i, t)| (*t, format!("{i}{}", "a".repeat(63))))
            .collect()
    }

    #[test]
    fn the_formula_names_every_target_with_its_checksum() {
        let text = formula("1.2.3", &sums());
        for (target, digest) in sums() {
            assert!(text.contains(&asset("1.2.3", target)), "{target}");
            assert!(text.contains(&format!("sha256 \"{digest}\"")), "{target}");
        }
        assert!(text.contains("version \"1.2.3\""));
        assert!(text.contains("#{version}"), "Ruby interpolation survives");
    }

    #[test]
    fn the_pkgbuild_carries_the_linux_targets() {
        let text = pkgbuild("1.2.3", &sums());
        assert!(text.contains("pkgver=1.2.3\n"));
        assert!(text.contains(&format!(
            "sha256sums_x86_64=('{}')",
            sums()["x86_64-unknown-linux-musl"]
        )));
        assert!(text.contains(&format!(
            "sha256sums_aarch64=('{}')",
            sums()["aarch64-unknown-linux-musl"]
        )));
        assert!(!text.contains("apple-darwin"));
        assert!(text.contains("package() {\n"));
    }

    #[test]
    fn dist_checksums_are_read_and_a_missing_one_is_named() {
        let dir = std::env::temp_dir().join(format!("xtask-dist-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).expect("mkdir");
        for (target, digest) in sums() {
            std::fs::write(
                dir.join(format!("{}.sha256", asset("1.2.3", target))),
                format!("{digest}  {}\n", asset("1.2.3", target)),
            )
            .expect("write");
        }
        assert_eq!(checksums_from_dist("1.2.3", &dir).expect("reads"), sums());
        std::fs::remove_file(dir.join(format!("{}.sha256", asset("1.2.3", TARGETS[2]))))
            .expect("rm");
        let error = checksums_from_dist("1.2.3", &dir).expect_err("one is missing");
        assert!(error.contains(TARGETS[2]), "{error}");
        std::fs::remove_dir_all(&dir).expect("cleanup");
    }
}
